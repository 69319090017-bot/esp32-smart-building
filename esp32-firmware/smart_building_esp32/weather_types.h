// weather_types.h - Data Structures for Weather & Multi-Hazard Alert Engine
#pragma once

#include <Arduino.h>

// Alert Severity Levels
enum class AlertSeverity : uint8_t {
    NORMAL = 0,
    WARNING = 1,
    CRITICAL = 2
};

// Hazard Kinds
enum class HazardKind : uint8_t {
    NONE = 0,
    UV = 1,          // High / Extreme UV Index
    HEAT = 2,        // Heat Index / Apparent Temperature (Heatstroke)
    STORM = 3,       // Thunderstorm / Hail (WMO 95, 96, 99)
    GUST = 4,        // Severe Wind Gusts
    RAIN = 5,        // Heavy / Torrential Rain
    FLOOD = 6        // River Discharge Flood Risk
};

inline const char* severityToString(AlertSeverity sev) {
    switch (sev) {
        case AlertSeverity::CRITICAL: return "CRITICAL";
        case AlertSeverity::WARNING:  return "WARNING";
        default:                      return "NORMAL";
    }
}

inline const char* hazardKindToString(HazardKind kind) {
    switch (kind) {
        case HazardKind::UV:    return "UV";
        case HazardKind::HEAT:  return "HEAT";
        case HazardKind::STORM: return "STORM";
        case HazardKind::GUST:  return "GUST";
        case HazardKind::RAIN:  return "RAIN";
        case HazardKind::FLOOD: return "FLOOD";
        default:                return "NONE";
    }
}

// Weather Snapshot struct holding raw field-to-field API metrics
struct WeatherSnapshot {
    char province[48] = "กรุงเทพมหานคร";
    char provinceEn[48] = "Bangkok";
    float latitude = 13.7563f;
    float longitude = 100.5018f;

    char observedAt[32] = "";       // ISO timestamp from API
    float temperature = 0.0f;       // °C (temperature_2m)
    float apparentTemperature = 0.0f; // °C (apparent_temperature)
    float humidity = 0.0f;          // % (relative_humidity_2m)
    float uvIndex = 0.0f;           // UV Index (uv_index)
    float windSpeed = 0.0f;         // km/h (wind_speed_10m)
    float windGusts = 0.0f;         // km/h (wind_gusts_10m)
    float precipitation = 0.0f;     // mm (precipitation)
    int weatherCode = 0;            // WMO code (weather_code)
    float riverDischarge = 0.0f;    // m³/s (river_discharge)

    bool valid = false;
    uint32_t fetchDurationMs = 0;
    uint32_t lastFetchEpoch = 0;
};

// Alert Payload generated by AlertEngine
struct AlertPayload {
    char alertId[64] = "";
    HazardKind kind = HazardKind::NONE;
    AlertSeverity severity = AlertSeverity::NORMAL;
    char province[48] = "";
    char message[192] = "";
    uint32_t timestamp = 0;
};
