import os
import re

def load_env(filepath):
    env = {}
    if not os.path.exists(filepath):
        return env
    with open(filepath, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            if '=' in line:
                key, val = line.split('=', 1)
                env[key.strip()] = val.strip()
    return env

def setup_secrets():
    # Detect project root directory
    base_dir = os.path.dirname(os.path.abspath(__file__))
    if os.path.exists(os.path.join(base_dir, 'secrets.example.env')):
        project_root = base_dir
    elif os.path.exists(os.path.join(base_dir, '..', 'secrets.example.env')):
        project_root = os.path.abspath(os.path.join(base_dir, '..'))
    else:
        project_root = os.path.abspath('.')

    secrets_file = os.path.join(project_root, 'secrets.env')
    example_file = os.path.join(project_root, 'secrets.example.env')

    if not os.path.exists(secrets_file) and os.path.exists(example_file):
        print("[INFO] Creating secrets.env from secrets.example.env...")
        with open(example_file, 'r', encoding='utf-8') as src:
            with open(secrets_file, 'w', encoding='utf-8') as dst:
                dst.write(src.read())

    secrets = load_env(secrets_file)
    if not secrets:
        print("Error: secrets.env not found or empty.")
        return

    # 1. Update ESP32 secrets.h (both root of esp32-firmware and smart_building_esp32)
    esp32_root = os.path.join(project_root, 'esp32-firmware')
    secrets_h_content = f"""#ifndef SECRETS_H
#define SECRETS_H

// 1. WiFi Credentials
#define SECRET_WIFI_SSID "{secrets.get('WIFI_SSID', '')}"
#define SECRET_WIFI_PASSWORD "{secrets.get('WIFI_PASSWORD', '')}"

// 2. Telegram Bot Credentials
#define SECRET_TELEGRAM_BOT_TOKEN "{secrets.get('TELEGRAM_BOT_TOKEN', '')}"
#define SECRET_TELEGRAM_CHAT_ID "{secrets.get('TELEGRAM_CHAT_ID', '')}"

// 3. MQTT Broker Settings
#define SECRET_MQTT_BROKER "{secrets.get('MQTT_BROKER', 'broker.hivemq.com')}"
#define SECRET_MQTT_PORT {secrets.get('MQTT_PORT', '1883')}

// 4. Firebase Cloud Realtime Database
#define SECRET_FIREBASE_URL "{secrets.get('FIREBASE_DATABASE_URL', '')}"
#define SECRET_FIREBASE_API_KEY "{secrets.get('FIREBASE_API_KEY', '')}"
#define SECRET_FIREBASE_AUTH_EMAIL "{secrets.get('ESP32_AUTH_EMAIL', '')}"
#define SECRET_FIREBASE_AUTH_PASSWORD "{secrets.get('ESP32_AUTH_PASSWORD', '')}"
#define SECRET_FIREBASE_ROOT_CA ""

// 5. Device Identity
#define SECRET_DEVICE_ID "{secrets.get('DEVICE_ID', 'smart_building_001')}"
#define SECRET_OTA_PASSWORD_HASH ""

#endif
"""
    targets = [
        os.path.join(project_root, 'esp32-firmware', 'secrets.h'),
        os.path.join(project_root, 'esp32-firmware', 'smart_building_esp32', 'secrets.h')
    ]
    for target in targets:
        os.makedirs(os.path.dirname(target), exist_ok=True)
        with open(target, 'w', encoding='utf-8') as f:
            f.write(secrets_h_content)
        print(f"[OK] Updated {target}")

    # 2. Update web-dashboard/.env.local (Git-ignored)
    web_dir = os.path.join(project_root, 'web-dashboard')
    web_env_path = os.path.join(web_dir, '.env.local')
    if os.path.exists(web_dir):
        web_env_content = f"""# Auto-generated by setup_secrets.py (2026 Edition)
VITE_FIREBASE_API_KEY={secrets.get('FIREBASE_API_KEY', '')}
VITE_FIREBASE_DATABASE_URL={secrets.get('FIREBASE_DATABASE_URL', '')}
VITE_FIREBASE_PROJECT_ID={secrets.get('FIREBASE_PROJECT_ID', '')}
VITE_FIREBASE_APP_ID={secrets.get('FIREBASE_APP_ID', '')}
VITE_DEVICE_ID={secrets.get('DEVICE_ID', 'smart_building_001')}
VITE_TELEGRAM_BOT_TOKEN={secrets.get('TELEGRAM_BOT_TOKEN', '')}
VITE_TELEGRAM_CHAT_ID={secrets.get('TELEGRAM_CHAT_ID', '')}
VITE_MQTT_BROKER={secrets.get('MQTT_BROKER', 'broker.hivemq.com')}
"""
        with open(web_env_path, 'w', encoding='utf-8') as f:
            f.write(web_env_content)
        print(f"[OK] Updated {web_env_path}")

    # 3. Update discord-bot/.env if exists
    discord_env_path = 'discord-bot/.env'
    if os.path.exists(os.path.dirname(discord_env_path)):
        bot_env_content = f"""# Auto-generated by setup_secrets.py
DISCORD_WEBHOOK_URL={secrets.get('DISCORD_WEBHOOK_URL', '')}
DISCORD_BOT_TOKEN={secrets.get('DISCORD_BOT_TOKEN', '')}
FIREBASE_DATABASE_URL={secrets.get('FIREBASE_DATABASE_URL', '')}
FIREBASE_API_KEY={secrets.get('FIREBASE_API_KEY', '')}
FIREBASE_AUTH_EMAIL={secrets.get('BOT_AUTH_EMAIL', '')}
FIREBASE_AUTH_PASSWORD={secrets.get('BOT_AUTH_PASSWORD', '')}
DEVICE_ID={secrets.get('DEVICE_ID', 'smart_building_001')}
PORT=8080
"""
        with open(discord_env_path, 'w', encoding='utf-8') as f:
            f.write(bot_env_content)
        print(f"[OK] Updated {discord_env_path}")

    print("\n[SUCCESS] All credentials synchronized successfully across ESP32, Web, and Cloud!")

if __name__ == '__main__':
    setup_secrets()
